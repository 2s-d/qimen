def seed_knowledge() -> None:
    """批量插入知识文章种子数据。"""
    db = SessionLocal()
    try:
        count_inserted = 0
        for data in ARTICLES:
            existing = (
                db.query(KnowledgeArticle)
                .filter(
                    KnowledgeArticle.category == data["category"],
                    KnowledgeArticle.title == data["title"],
                )
                .first()
            )
            if existing:
                continue
            article = KnowledgeArticle(**data)
            db.add(article)
            count_inserted += 1

        db.commit()
        print(f"✅ 知识文章种子数据插入完成，本次新增 {count_inserted} 条")
    except Exception as e:
        db.rollback()
        print(f"❌ 知识文章种子数据插入失败: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_knowledge()
